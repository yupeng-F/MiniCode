#!/usr/bin/env node
// 此文档是 MAI-Harness 框架的一部分，请勿在项目中修改，请在框架工程中修改，并覆盖到此项目中。
// =============================================================================
// Harness migrate-deploy-config — 一次性迁移工具
//
// 将旧 config/environments.yml + config/build-targets.yml 合成为 config/deploy.yml，
// 然后将旧文件备份到 .harness/migrations/<timestamp>/ 并从 config/ 删除（避免双源漂移）。
//
// 由 install.sh 在检测到旧文件 + 缺 deploy.yml 时调用；也可手动执行。
// 幂等：deploy.yml 已存在则跳过（不重复迁移、不再次清理）。
// 选项：--keep-legacy 保留旧文件不删除（仅备份），用于先校核再人工删
// =============================================================================

import { existsSync, writeFileSync, renameSync, mkdirSync, copyFileSync } from 'node:fs';
import { join } from 'node:path';
import yaml from 'js-yaml';
import { loadDeployConfig } from './lib/deploy-config.mjs';

const TARGET = 'config/deploy.yml';
const KEEP_LEGACY = process.argv.includes('--keep-legacy');
const LEGACY_FILES = [
  'config/environments.yml',
  'config/build-targets.yml',
  'config/build-targets.example.yml',
];

if (existsSync(TARGET)) {
  console.log(`[migrate-deploy-config] ${TARGET} 已存在，跳过`);
  process.exit(0);
}

if (!existsSync('config/environments.yml')) {
  console.error('[migrate-deploy-config] config/environments.yml 不存在，无法迁移');
  process.exit(1);
}

try {
  const cfg = loadDeployConfig();
  const { _source, ...clean } = cfg;
  writeFileSync(TARGET,
    '# AUTO-GENERATED by scripts/migrate-deploy-config.mjs from environments.yml + build-targets.yml\n' +
    yaml.dump(clean));
  console.log(`[migrate-deploy-config] ${TARGET} 已生成`);
} catch (e) {
  console.error(`[migrate-deploy-config] 失败: ${e.message}`);
  process.exit(1);
}

// 备份并清理旧文件（避免双源漂移）
const stamp = new Date().toISOString().replace(/[:.]/g, '-');
const backupDir = join('.harness', 'migrations', `deploy-config-${stamp}`);
mkdirSync(backupDir, { recursive: true });

let movedCount = 0;
for (const f of LEGACY_FILES) {
  if (!existsSync(f)) continue;
  const dest = join(backupDir, f.replace(/\//g, '__'));
  if (KEEP_LEGACY) {
    copyFileSync(f, dest);
    console.log(`[migrate-deploy-config] backed up: ${f} → ${dest} (--keep-legacy)`);
  } else {
    renameSync(f, dest);
    console.log(`[migrate-deploy-config] moved: ${f} → ${dest}`);
    movedCount++;
  }
}

if (KEEP_LEGACY) {
  console.log(`[migrate-deploy-config] --keep-legacy 已设置；请校核 ${TARGET} 后手动删除旧文件`);
} else if (movedCount > 0) {
  console.log(`[migrate-deploy-config] ✅ 旧配置已迁移到 ${backupDir}（如需回退：mv 回 config/）`);
}
